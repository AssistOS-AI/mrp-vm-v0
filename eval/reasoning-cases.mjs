function makeValidation(pattern, message) {
  return { pattern, message };
}

function escapeRegex(text) {
  return String(text).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function makeSectionValidations(sectionNames = []) {
  return sectionNames.map((name) => makeValidation(new RegExp(`${escapeRegex(name)}:`, 'i'), `Missing ${name} section.`));
}

function joinProgram(program) {
  return [program].flat().join('\n');
}

function buildJsonEnvelopeScript(problem, extra = {}) {
  return `return ${JSON.stringify(JSON.stringify({
    problem,
    result_mode: 'text',
    ...extra,
  }))};`;
}

function buildDeliveryTemplate(stepLines = [], refName = 'reasoning') {
  return [
    'Execution steps:',
    ...stepLines.map((line, index) => `${index + 1}. ${line}`),
    '',
    `$${refName}`,
  ].join('\n');
}

function buildHumanLikeShowcaseScenario(problem, program, options = {}) {
  const requestTarget = options.requestTarget ?? 'reasoning_request';
  const reasoningTarget = options.reasoningTarget ?? 'reasoning';
  const deliveryTarget = options.deliveryTarget ?? 'delivery';
  const planMinDeclarations = options.planMinDeclarations ?? 4;
  const stepLines = options.stepLines ?? [
    'Frame the bounded problem in a machine-friendly form.',
    'Solve the core reasoning step explicitly.',
    'Return the answer using the requested sections.',
  ];

  if (options.useLogicEval) {
    return {
      planMinDeclarations,
      scriptedSequences: {
        plannerLLM: [[
          `@${requestTarget} logic-eval`,
          options.rewriteInstruction ?? 'Rewrite the request into a bounded reasoning brief that preserves the required sections and keeps the task finite.',
          '',
          `@${reasoningTarget} HumanLikeReasoner`,
          `$${requestTarget}`,
          '',
          `@${deliveryTarget} template-eval`,
          buildDeliveryTemplate(stepLines, reasoningTarget),
          '',
          '@response template-eval',
          `$${deliveryTarget}`,
        ].join('\n')],
        logicGeneratorLLM: [
          JSON.stringify({
            status: 'rewrite_ready',
            rewritten_problem: options.rewriteProblem ?? problem,
            decomposition_hints: options.decompositionHints ?? [
              'Keep the reasoning bounded and explicit.',
              'Preserve the requested output sections exactly.',
            ],
            answer_requirements: options.answerRequirements ?? [],
          }),
          joinProgram(program),
        ],
      },
    };
  }

  return {
    planMinDeclarations,
    scriptedSequences: {
      plannerLLM: [[
        `@${requestTarget} js-eval`,
        buildJsonEnvelopeScript(problem, options.extraEnvelopeFields),
        '',
        `@${reasoningTarget} HumanLikeReasoner`,
        `$${requestTarget}`,
        '',
        `@${deliveryTarget} template-eval`,
        buildDeliveryTemplate(stepLines, reasoningTarget),
        '',
        '@response template-eval',
        `$${deliveryTarget}`,
      ].join('\n')],
      logicGeneratorLLM: [[joinProgram(program)].join('\n')],
    },
  };
}

