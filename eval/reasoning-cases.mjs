function buildDocumentShowcaseScenario(config = {}) {
  const sourceTarget = config.sourceTarget ?? 'document_source';
  const planTarget = config.planTarget ?? 'document_plan';
  const deliveryTarget = config.deliveryTarget ?? 'document_delivery';
  const finalTarget = config.finalTarget ?? 'document_result';
  const sourceBody = typeof config.source === 'string'
    ? `return ${JSON.stringify(config.source)};`
    : `return ${JSON.stringify(JSON.stringify(config.source, null, 2))};`;
  return {
    planMinDeclarations: config.planMinDeclarations ?? 4,
    scriptedSequences: {
      plannerLLM: [[
        `@${sourceTarget} js-eval`,
        sourceBody,
        '',
        `@${planTarget} DocumentScalePlanner`,
        `document_ref ~${sourceTarget}`,
        JSON.stringify({
          document_ref: `~${sourceTarget}`,
          operation: config.operation,
          granularity: config.granularity,
          final_target: finalTarget,
          task: config.task,
          path: config.path,
          text_field: config.textField,
        }),
        '',
        `@${deliveryTarget} template-eval`,
        buildDeliveryTemplate(config.stepLines ?? [
          'Materialize the source document as a bounded runtime value.',
          'Split the document into local work units and produce rollups.',
          'Return the final synthesis with the requested sections.',
        ], planTarget),
        '',
        '@response template-eval',
        `$${deliveryTarget}`,
      ].join('\n')],
      writerLLM: [...(config.writerOutputs ?? [])],
    },
  };
}

